"""Conquer Health hackathon evaluation splits.

Two fixed, disjoint slices of HealthBench Main, generated by
``scripts/make_conquer_split.py``:

- ``conquer_val``  — published. Teams iterate against it; it drives the live
  leaderboard. Its prompt ids ship inside the package.
- ``conquer_test`` — held out. Decides the final ranking. Its prompt id list
  must live OUTSIDE this repository: every HealthBench prompt and rubric is
  public, so the only thing protecting the test set is *which items were
  chosen*. ``ids_path`` is therefore required, with no default.

Both splits are theme-stratified and matched on rubric structure, so the val
score is an unbiased (if noisier) estimate of the test score. That is what makes
per-item gaming self-punishing rather than merely unlucky.

Ordering is deterministic (sorted by ``prompt_id``), so ``sample_id`` N refers to
the same item for every team on every run. Cross-team comparison and the
common-item intersection used for ranking both depend on that.
"""

from __future__ import annotations

import json
import logging
from importlib import resources
from pathlib import Path

from coeval.core.registry import register_dataset
from coeval.core.types import ConversationalGolden
from coeval.datasets.healthbench import MAIN_URL, _HealthBenchDatasetBase

logger = logging.getLogger(__name__)

VAL_IDS_RESOURCE = "conquer_val_ids.json"


def _read_ids(path: str | Path) -> tuple[list[str], dict]:
    payload = json.loads(Path(path).read_text())
    ids = payload.get("prompt_ids")
    if not ids:
        raise ValueError(f"{path} contains no 'prompt_ids'")
    return ids, payload


class _ConquerSplitDataset(_HealthBenchDatasetBase):
    """HealthBench Main filtered to an explicit prompt-id list."""

    _URL = MAIN_URL
    _SPLIT: str

    def __init__(
        self,
        ids_path: str | Path | None = None,
        num_samples: int | None = None,
        **kwargs,
    ) -> None:
        self._ids_path = ids_path
        self._split_meta: dict = {}
        # sample_ratio/seed are meaningless here: the split is a fixed list.
        super().__init__(num_samples=num_samples, sample_ratio=None, **kwargs)

    def _resolve_ids(self) -> tuple[list[str], dict]:
        if self._ids_path is not None:
            return _read_ids(self._ids_path)
        raise ValueError(
            f"{type(self).__name__} requires ids_path — the {self._SPLIT} id list is "
            "not shipped in this package."
        )

    def _load(
        self,
        num_samples: int | None,
        sample_ratio: float | None,  # noqa: ARG002 — fixed list, not sampled
        seed: int,  # noqa: ARG002
    ) -> list[ConversationalGolden]:
        wanted_ids, meta = self._resolve_ids()
        self._split_meta = {k: v for k, v in meta.items() if k != "prompt_ids"}
        wanted = set(wanted_ids)

        lines = self._read_or_download(self._URL).strip().split("\n")
        by_id: dict[str, ConversationalGolden] = {}
        for line in lines:
            row = json.loads(line)
            if row.get("prompt_id") not in wanted:
                continue
            golden = self._build_golden(row)
            if golden is not None:
                by_id[row["prompt_id"]] = golden

        # A missing id means the id list and the upstream JSONL have diverged.
        # Silently scoring a short set would make runs incomparable, so fail loud.
        missing = wanted - by_id.keys()
        if missing:
            raise ValueError(
                f"{len(missing)} of {len(wanted)} {self._SPLIT} prompt_ids not found in "
                f"HealthBench Main (e.g. {sorted(missing)[:3]}). The id list and the "
                "upstream dataset have diverged; regenerate the split."
            )

        # Deterministic order — sample_id N must mean the same item for every team.
        goldens = [by_id[pid] for pid in sorted(by_id)]
        if num_samples is not None:
            goldens = goldens[:num_samples]
            logger.warning(
                "Truncated %s to %d samples — smoke-test only, not a comparable score.",
                self._SPLIT,
                len(goldens),
            )

        logger.info("Loaded %d Conquer Health %s samples", len(goldens), self._SPLIT)
        return goldens


@register_dataset("conquer_val")
class ConquerHealthValDataset(_ConquerSplitDataset):
    """Published validation split (~300 examples) driving the live leaderboard."""

    _SPLIT = "val"
    _LABEL = "ConquerVal"

    def _resolve_ids(self) -> tuple[list[str], dict]:
        if self._ids_path is not None:
            return _read_ids(self._ids_path)
        with resources.as_file(
            resources.files("coeval.data").joinpath(VAL_IDS_RESOURCE)
        ) as path:
            return _read_ids(path)

    @property
    def name(self) -> str:
        return "ConquerHealthVal"


@register_dataset("conquer_test")
class ConquerHealthTestDataset(_ConquerSplitDataset):
    """Held-out test split (500 examples) deciding the final ranking.

    ``ids_path`` is mandatory and must point outside the repository.
    """

    _SPLIT = "test"
    _LABEL = "ConquerTest"

    @property
    def name(self) -> str:
        return "ConquerHealthTest"
